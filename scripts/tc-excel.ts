/**
 * Exports test-cases/json/<module>.json to test-cases/excel/<Module>_TestCases.xlsx
 * with three sheets: Summary, Test Cases, Traceability. JSON stays the source of truth;
 * the workbook is regenerated, never edited by hand.
 *
 *   npm run tc:excel            -> every module
 *   npm run tc:excel -- pim     -> one module
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import ExcelJS from 'exceljs';
import { loadSuites, requirementIdsIn, scopeOf, type Suite } from './lib/testCases';

const OUT = path.resolve('test-cases/excel');
const ORANGE = 'FFE8702A';
const DARK = 'FF2F3B45';
const FILL: Record<string, string> = { Positive: 'FFE6F4EA', Negative: 'FFFDE7E7', Edge: 'FFFFF4E0' };

function header(ws: ExcelJS.Worksheet) {
  const row = ws.getRow(1);
  row.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  row.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: DARK } };
  row.alignment = { vertical: 'middle', wrapText: true };
  row.height = 24;
  ws.views = [{ state: 'frozen', ySplit: 1 }];
  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: ws.columnCount } };
}

function border(ws: ExcelJS.Worksheet) {
  ws.eachRow((r) =>
    r.eachCell((c) => {
      c.border = {
        top: { style: 'thin', color: { argb: 'FFC9CED3' } },
        bottom: { style: 'thin', color: { argb: 'FFC9CED3' } },
        left: { style: 'thin', color: { argb: 'FFC9CED3' } },
        right: { style: 'thin', color: { argb: 'FFC9CED3' } },
      };
    }),
  );
}

async function exportSuite(suite: Suite) {
  const wb = new ExcelJS.Workbook();
  wb.creator = suite.generatedBy;
  wb.created = new Date();
  const cases = suite.testCases;

  // Summary
  const sum = wb.addWorksheet('Summary', { properties: { tabColor: { argb: ORANGE } } });
  sum.columns = [{ width: 32 }, { width: 14 }, { width: 14 }, { width: 14 }, { width: 14 }];
  sum.addRow([`${suite.module} - Manual Test Cases`]).font = {
    bold: true,
    size: 16,
    color: { argb: ORANGE },
  };
  sum.addRow([`Source: ${suite.source}`]);
  sum.addRow([
    `Version ${suite.version} · generated by ${suite.generatedBy} · exported ${new Date().toISOString().slice(0, 10)}`,
  ]);
  sum.addRow([]);
  const t = sum.addRow(['Feature', 'Positive', 'Negative', 'Edge', 'Total']);
  t.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  t.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: DARK } };
  const features = [...new Set(cases.map((c) => c.feature))];
  for (const layer of ['UI', 'API'] as const) {
    const lc = cases.filter((c) => c.layer === layer);
    if (!lc.length) continue;
    sum.addRow([`${layer} layer`]).font = { bold: true };
    for (const f of features) {
      const fc = lc.filter((c) => c.feature === f);
      if (!fc.length) continue;
      sum.addRow([
        f,
        ...(['Positive', 'Negative', 'Edge'] as const).map((k) => fc.filter((c) => c.type === k).length),
        fc.length,
      ]);
    }
  }
  const tot = sum.addRow([
    'Total',
    ...(['Positive', 'Negative', 'Edge'] as const).map((k) => cases.filter((c) => c.type === k).length),
    cases.length,
  ]);
  tot.font = { bold: true };
  sum.addRow([]);
  sum.addRow(['Automated', cases.filter((c) => c.automation.status === 'Automated').length]);
  sum.addRow(['Planned', cases.filter((c) => c.automation.status === 'Planned').length]);
  sum.addRow(['Manual only', cases.filter((c) => c.automation.status === 'Manual').length]);
  for (const p of ['P1', 'P2', 'P3'])
    sum.addRow([`Priority ${p}`, cases.filter((c) => c.priority === p).length]);

  // Test Cases
  const ws = wb.addWorksheet('Test Cases');
  ws.columns = [
    { header: 'TC ID', key: 'id', width: 15 },
    { header: 'Feature', key: 'feature', width: 22 },
    { header: 'Title', key: 'title', width: 46 },
    { header: 'Layer', key: 'layer', width: 7 },
    { header: 'Type', key: 'type', width: 10 },
    { header: 'Priority', key: 'priority', width: 9 },
    { header: 'Roles', key: 'roles', width: 12 },
    { header: 'Requirement IDs', key: 'reqs', width: 22 },
    { header: 'Preconditions', key: 'pre', width: 34 },
    { header: 'Test Data', key: 'data', width: 30 },
    { header: 'API', key: 'api', width: 30 },
    { header: 'Steps', key: 'steps', width: 55 },
    { header: 'Expected per step', key: 'exp', width: 55 },
    { header: 'Expected Result', key: 'result', width: 40 },
    { header: 'Tags', key: 'tags', width: 18 },
    { header: 'Automation', key: 'auto', width: 12 },
    { header: 'Spec / Reason', key: 'spec', width: 36 },
    { header: 'Actual Result', key: 'actual', width: 24 },
    { header: 'Status', key: 'status', width: 12 },
  ];
  for (const c of cases) {
    const row = ws.addRow({
      id: c.id,
      feature: c.feature,
      title: c.title,
      layer: c.layer,
      type: c.type,
      priority: c.priority,
      roles: (c.roles ?? []).join(', '),
      reqs: c.requirementIds.join('\n'),
      pre: c.preconditions.map((p, i) => `${i + 1}. ${p}`).join('\n'),
      data: c.testData
        ? Object.entries(c.testData)
            .map(([k, v]) => `${k}: ${typeof v === 'string' ? v : JSON.stringify(v)}`)
            .join('\n')
        : '',
      api: c.api ? `${c.api.method} ${c.api.endpoint}\n→ ${c.api.expectedStatus}` : '',
      steps: c.steps.map((s, i) => `${i + 1}. ${s.action}`).join('\n'),
      exp: c.steps.map((s, i) => `${i + 1}. ${s.expected}`).join('\n'),
      result: c.expectedResult,
      tags: (c.tags ?? []).join(' '),
      auto: c.automation.status,
      spec: c.automation.spec ?? c.automation.reason ?? '',
      actual: '',
      status: 'Not Run',
    });
    row.alignment = { vertical: 'top', wrapText: true };
    row.getCell('type').fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: FILL[c.type] } };
  }
  ws.getColumn('status').eachCell((cell, n) => {
    if (n > 1)
      cell.dataValidation = {
        type: 'list',
        allowBlank: true,
        formulae: ['"Not Run,Pass,Fail,Blocked,Skipped"'],
      };
  });
  header(ws);
  border(ws);

  // Traceability
  const tr = wb.addWorksheet('Traceability');
  tr.columns = [
    { header: 'Requirement ID', key: 'req', width: 22 },
    { header: 'Test Cases', key: 'tcs', width: 60 },
    { header: 'Count', key: 'n', width: 8 },
  ];
  const map = new Map<string, string[]>();
  const known = fs.existsSync(suite.source)
    ? [...requirementIdsIn(suite.source)].filter((r) => /-AC\d+$/.test(r) && scopeOf(suite).test(r))
    : [];
  for (const r of known) map.set(r, []);
  for (const c of cases) for (const r of c.requirementIds) map.set(r, [...(map.get(r) ?? []), c.id]);
  for (const [req, tcs] of [...map.entries()].sort(([a], [b]) =>
    a.localeCompare(b, 'en', { numeric: true }),
  )) {
    const row = tr.addRow({ req, tcs: tcs.join(', '), n: tcs.length });
    if (!tcs.length)
      row.getCell('n').fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFFDE7E7' } };
  }
  header(tr);
  border(tr);

  fs.mkdirSync(OUT, { recursive: true });
  const file = path.join(OUT, `${suite.module.replace(/\W+/g, '_')}_TestCases.xlsx`);
  await wb.xlsx.writeFile(file);
  console.log(`${suite.module}: ${cases.length} cases -> ${path.relative(process.cwd(), file)}`);
}

(async () => {
  for (const { suite } of loadSuites(process.argv.slice(2))) await exportSuite(suite);
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
