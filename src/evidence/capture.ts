import { createHash } from 'node:crypto';
import { test, type Locator, type Page, type TestInfo } from '@playwright/test';
import { env } from '@config/env';
import { logger } from '@utils/logger';

const log = logger('evidence');

/** Attachment name prefix of evidence screenshots: `evidence #007: Verify header name "..."`. */
export const EVIDENCE_PREFIX = 'evidence #';
/** JSON attachment with one entry per screenshot (url, time, status), written by the `_evidence` auto fixture. */
export const EVIDENCE_INDEX = 'evidence-index';

export interface EvidenceEntry {
  n: number;
  caption: string;
  /** Page URL at capture time. */
  url: string;
  time: string;
  /** Milliseconds since the test started. */
  elapsedMs: number;
  status: 'passed' | 'failed';
  attachment: string;
}

interface EvidenceState {
  entries: EvidenceEntry[];
  lastHash?: string;
  started: number;
}

const states = new WeakMap<TestInfo, EvidenceState>();

function stateFor(info: TestInfo): EvidenceState {
  let state = states.get(info);
  if (!state) {
    state = { entries: [], started: Date.now() };
    states.set(info, state);
  }
  return state;
}

/** Marks the start of a test so `elapsedMs` of every screenshot is relative to it. */
export function beginEvidence(info: TestInfo): void {
  stateFor(info);
}

export function evidenceEntries(info: TestInfo): EvidenceEntry[] {
  return states.get(info)?.entries ?? [];
}

export function isPage(subject: Page | Locator): subject is Page {
  return typeof (subject as Locator).page !== 'function';
}

/** `getByRole('button', { name: 'Save' })` for a locator, `page` for a page. */
export function describeSubject(subject: Page | Locator): string {
  return isPage(subject) ? 'page' : String(subject).replace(/^Locator@/, '');
}

const SECRET_PATTERNS: RegExp[] = [
  // JSON / object notation: "password":"x", password: 'x'
  /((?:password|passwd|secret|token)["']?\s*[:=]\s*)(["'])(?:(?!\2).)*\2/gi,
  // Passwords generated by dataFactory.password(): Qa + 6 alphanumerics + # + 2 digits
  /\bQa[A-Za-z0-9]{6}#\d{2}\b/g,
];
const knownSecrets = new Set<string>([env.admin.password].filter((s) => s.length >= 4));

/** Registers a secret value so it is replaced by `***` in event logs and captions. */
export function registerSecret(value: string): void {
  if (value && value.length >= 4) knownSecrets.add(value);
}

/**
 * Hides secrets: known values (Admin password, registered ones), generated passwords, `password: "x"`
 * pairs, and the typed value of `Fill "x"` / `Type "x"` on a line that mentions a password field.
 */
export function maskSecrets(text: string): string {
  let out = text;
  for (const secret of knownSecrets) out = out.split(secret).join('***');
  out = out.replace(
    SECRET_PATTERNS[0],
    (_m, prefix: string, quote: string) => `${prefix}${quote}***${quote}`,
  );
  out = out.replace(SECRET_PATTERNS[1], '***');
  if (/password/i.test(out)) out = out.replace(/\b(Fill|Type|Press sequentially)\s+"[^"]*"/g, '$1 "***"');
  return out;
}

/**
 * Takes a viewport screenshot of the subject's page and attaches it to the running test as
 * `evidence #NNN: <caption>` (JPEG). Consecutive identical screenshots are skipped unless `force`
 * is set, so a run of assertions on one screen yields a single picture. Never throws: evidence must
 * not change a test's outcome (a page may be closed or navigating when an assertion completes).
 * Set `EVIDENCE=off` to disable capturing.
 */
export async function captureEvidence(
  caption: string,
  subject: Page | Locator,
  opts: { force?: boolean; status?: 'passed' | 'failed' } = {},
): Promise<void> {
  if (process.env.EVIDENCE === 'off') return;
  let info: TestInfo;
  try {
    info = test.info();
  } catch {
    return; // outside a test (e.g. a worker fixture): nothing to attach to
  }
  const state = stateFor(info);
  try {
    const page = isPage(subject) ? subject : subject.page();
    if (page.isClosed()) return;
    if (!isPage(subject)) {
      // Bring the asserted element into the viewport; hidden or detached elements are captured as is.
      try {
        await subject.first().scrollIntoViewIfNeeded({ timeout: 1_500 });
      } catch {
        /* ignore */
      }
    }
    const body = await page.screenshot({ type: 'jpeg', quality: 65, timeout: 5_000 });
    const hash = createHash('sha1').update(body).digest('hex');
    if (!opts.force && hash === state.lastHash) return;
    state.lastHash = hash;

    const n = state.entries.length + 1;
    const name = `${EVIDENCE_PREFIX}${String(n).padStart(3, '0')}: ${maskSecrets(caption)}`;
    await info.attach(name, { body, contentType: 'image/jpeg' });
    state.entries.push({
      n,
      caption: maskSecrets(caption),
      url: page.url(),
      time: new Date().toISOString(),
      elapsedMs: Date.now() - state.started,
      status: opts.status ?? 'passed',
      attachment: name,
    });
  } catch (error) {
    log.debug(`evidence screenshot skipped (${caption}): ${(error as Error).message}`);
  }
}
